function flashPad(i) {
  const el = document.querySelector(`[data-pad="${i}"]`);
  if (!el) return;
  el.classList.add("si-lit");
  setTimeout(() => el.classList.remove("si-lit"), 220);
}

function playSimonSequence() {
  const s = simonState;
  simonPlaying = true;
  render();
  let i = 0;
  const step = () => {
    if (i >= s.sequence.length) {
      simonPlaying = false;
      render();
      return;
    }
    flashPad(s.sequence[i]);
    i++;
    setTimeout(step, 520);
  };
  setTimeout(step, 400);
}

