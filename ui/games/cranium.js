/* ==========================================================================
   Puzzle books.
   ==========================================================================
   Cam: "a book system, where I can add generated puzzles to a book and
   name them. Then I can print the book all at once and it will have all
   the puzzles in it. Each one should have its own default cover."

   WHAT CAN GO IN A BOOK. Only puzzles that genuinely work on paper:
   Sudoku, Word Search, Nonogram, Futoshiki and Kakuro. Deliberately
   NOT 2048 (needs sliding), Simon (needs flashing), Memory (needs
   hidden cards), Mastermind or Hangman (need a hidden answer that
   responds to guesses), the sliding puzzle or Hanoi (need pieces that
   move). Printing those would produce a page nobody can do.

   WHAT'S STORED. The puzzle's own definition, not a picture of it — so
   a book re-prints at any size, and the answer pages can be generated
   from the same data rather than stored twice.
   ========================================================================== */
"use strict";

/* Which games can be printed, and how to snapshot one. Each grabs the
   minimum needed to redraw the puzzle AND its answer later. */
const BOOKABLE = {
  sudoku: {
    name: "Sudoku",
    /* BUG FIX — Cam: "When i click add to book nothing happens."
       This read st.puzzle, but the live Sudoku state stores its board
       as `grid` (with `given` marking the clues). st.puzzle was
       undefined, so .slice() threw and the dialog never opened.

       `grid` holds the CURRENT board including anything Cam has typed
       in, so the clue-only puzzle is rebuilt from `given` — otherwise
       a half-solved Sudoku would print with the answers already
       filled in. */
    snapshot: (st) => ({
      puzzle: st.grid.map((v, i) => (st.given[i] ? v : 0)),
      solution: st.solution.slice(),
      difficulty: st.difficulty,
    }),
    label: (p) => `Sudoku \u2014 ${p.difficulty}`,
  },
  wordsearch: {
    name: "Word Search",
    snapshot: (st) => ({grid: st.puzzle.grid.map((r) => r.slice()),
                        size: st.puzzle.size,
                        placed: st.puzzle.placed.map((p) => ({word: p.word,
                          cells: p.cells.map((c) => c.slice())})),
                        listName: st.listName}),
    label: (p) => `Word Search \u2014 ${p.listName}`,
  },
  nonogram: {
    name: "Nonogram",
    snapshot: (st) => ({size: st.puzzle.size,
                        rowClues: st.puzzle.rowClues.map((c) => c.slice()),
                        colClues: st.puzzle.colClues.map((c) => c.slice()),
                        solution: st.puzzle.solution.map((r) => r.slice()),
                        sizeName: st.puzzle.sizeName}),
    label: (p) => `Nonogram \u2014 ${p.size}\u00d7${p.size}`,
  },
  futoshiki: {
    name: "Futoshiki",
    /* stores the CLUES, not the working grid - so a part-solved puzzle
       prints blank, the same trap Sudoku hit */
    snapshot: (st) => ({n: st.puzzle.n,
                        clues: st.puzzle.clues.map((r) => r.slice()),
                        constraints: st.puzzle.constraints.map((x) => ({...x})),
                        solution: st.puzzle.solution.map((r) => r.slice()),
                        sizeName: st.puzzle.sizeName}),
    label: (p) => `Futoshiki \u2014 ${p.n}\u00d7${p.n}`,
  },
  kakuro: {
    name: "Kakuro",
    snapshot: (st) => ({rows: st.puzzle.rows, cols: st.puzzle.cols,
                        walls: st.puzzle.walls.map((r) => r.slice()),
                        clues: st.puzzle.clues.map((r) =>
                          r.map((x) => (x ? {...x} : null))),
                        solution: st.puzzle.solution.map((r) => r.slice()),
                        size: st.puzzle.size}),
    label: (p) => `Kakuro \u2014 ${p.rows}\u00d7${p.cols}`,
  },
};

const booksAll = () => (data.books || []);

function bookById(id) {
  return booksAll().find((b) => b.id === id) || null;
}

async function createBook(name) {
  data.books = data.books || [];
  const book = {id: "bk" + Date.now().toString(36),
                name: String(name).trim() || "Untitled",
                created: new Date().toISOString(), puzzles: []};
  data.books.push(book);
  await CR.Store.saveData(data);
  return book;
}

/** Offers the existing books plus "new book", then saves the puzzle.
    Cam: "At any one time i should be able to add to a book or create a
    new one" — so both routes are on the same sheet rather than the new
    book being hidden behind a separate menu. */
function addToBookDialog(gameKey, state) {
  const spec = BOOKABLE[gameKey];
  if (!spec) { toast("This one can't be printed on paper.", "error"); return; }
  /* A snapshot reads directly from a game's live state, so it breaks
     the moment that state's shape changes - and it broke exactly that
     way once (Sudoku's board is `grid`, not `puzzle`). Catching it
     here means a mismatch shows a real message instead of the button
     appearing to do nothing at all. */
  let snap;
  try {
    snap = spec.snapshot(state);
  } catch (err) {
    toast("Couldn't add that one to a book \u2014 sorry.", "error");
    console.error("book snapshot failed for " + gameKey, err);
    return;
  }
  const books = booksAll();

  const d = openDlg("Add to a book", `
    <p class="stamp" style="margin:0 0 12px">${esc(spec.label(snap))}</p>
    ${books.length ? `
      <label class="label" style="margin-top:0">Add to</label>
      <div id="bk-list">
        ${books.map((b) => `
          <button class="btn btn-block bk-choice" data-book="${escA(b.id)}"
            style="justify-content:space-between;margin-bottom:6px">
            <span>${esc(b.name)}</span>
            <span class="stamp">${b.puzzles.length} puzzle${
              b.puzzles.length === 1 ? "" : "s"}</span>
          </button>`).join("")}
      </div>
      <label class="label">Or start a new one</label>`
      : `<label class="label" style="margin-top:0">Name your first book</label>`}
    <div class="row" style="gap:8px">
      <input class="input" id="bk-new" style="flex:1"
             placeholder="Holiday puzzles">
      <button class="btn btn-good" id="bk-create">Create & add</button>
    </div>`);

  const put = async (book) => {
    book.puzzles.push({id: "pz" + Date.now().toString(36),
                       game: gameKey, added: new Date().toISOString(),
                       data: snap});
    await CR.Store.saveData(data);
    d.close();
    toast(`Added to ${book.name}.`, "good");
    render();
  };

  d.body.querySelectorAll("[data-book]").forEach((b) =>
    b.addEventListener("click", () => put(bookById(b.dataset.book))));

  d.body.querySelector("#bk-create").onclick = async () => {
    const name = d.body.querySelector("#bk-new").value.trim();
    if (!name) { toast("Give the book a name.", "error"); return; }
    put(await createBook(name));
  };
  d.btn("Cancel", "btn-quiet", d.close);
}

