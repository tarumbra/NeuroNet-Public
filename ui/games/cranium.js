/* ---- games/futoshiki.js ---- */
/* ==========================================================================
   Futoshiki — generator and solver.
   ==========================================================================
   Fill an n×n grid with 1..n so no digit repeats in any row or column
   (a Latin square), while satisfying the "<" and ">" signs shown
   between adjacent cells.

   Same non-negotiable as Sudoku and Nonogram: exactly ONE solution.
   Generated the reliable way round — build a complete valid grid
   first, derive every possible inequality from it (so the signs are
   correct by construction), then strip clues back while checking after
   each removal that the solution is still unique. Anything that would
   make it ambiguous goes straight back.
   ========================================================================== */
(function (root) {
  "use strict";

  const SIZES = {small: 4, medium: 5, large: 6};

  const shuffled = (arr) => {
    const a = arr.slice();
    for (let i = a.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
  };

  /** A complete, randomised Latin square of side n. */
  function generateSolved(n) {
    const grid = [];
    for (let r = 0; r < n; r++) grid.push(new Array(n).fill(0));
    const ok = (function fill(pos) {
      if (pos === n * n) return true;
      const r = Math.floor(pos / n), c = pos % n;
      for (const v of shuffled([...Array(n).keys()].map((x) => x + 1))) {
        let clash = false;
        for (let i = 0; i < n; i++) {
          if (grid[r][i] === v || grid[i][c] === v) { clash = true; break; }
        }
        if (clash) continue;
        grid[r][c] = v;
        if (fill(pos + 1)) return true;
        grid[r][c] = 0;
      }
      return false;
    })(0);
    return ok ? grid : null;
  }

  /** Every inequality between horizontally or vertically adjacent
      cells, read off the solved grid. Each is {r, c, dir, sign} where
      dir is "h" (this cell vs the one right) or "v" (vs the one
      below), and sign is "<" or ">". */
  function allConstraints(grid, n) {
    const out = [];
    for (let r = 0; r < n; r++) {
      for (let c = 0; c < n; c++) {
        if (c + 1 < n) {
          out.push({r, c, dir: "h",
                    sign: grid[r][c] < grid[r][c + 1] ? "<" : ">"});
        }
        if (r + 1 < n) {
          out.push({r, c, dir: "v",
                    sign: grid[r][c] < grid[r + 1][c] ? "<" : ">"});
        }
      }
    }
    return out;
  }

  const key = (con) => `${con.r},${con.c},${con.dir}`;

  /** Does `grid` (possibly partial) break any constraint that's fully
      determined? A constraint touching a blank cell can't be judged
      yet, so it's skipped rather than treated as a failure. */
  function violates(grid, n, cons) {
    for (const con of cons) {
      const a = grid[con.r][con.c];
      const b = con.dir === "h" ? grid[con.r][con.c + 1]
                                : grid[con.r + 1][con.c];
      if (!a || !b) continue;
      if (con.sign === "<" ? !(a < b) : !(a > b)) return true;
    }
    return false;
  }

  /** Counts solutions up to `limit`, stopping as soon as it can. Only
      ever asked "is there more than one?". */
  function countSolutions(clues, cons, n, limit) {
    limit = limit || 2;
    const grid = clues.map((row) => row.slice());
    let found = 0;
    (function solve(pos) {
      if (found >= limit) return;
      while (pos < n * n && grid[Math.floor(pos / n)][pos % n] !== 0) pos++;
      if (pos === n * n) { found++; return; }
      const r = Math.floor(pos / n), c = pos % n;
      for (let v = 1; v <= n; v++) {
        let clash = false;
        for (let i = 0; i < n; i++) {
          if (grid[r][i] === v || grid[i][c] === v) { clash = true; break; }
        }
        if (clash) continue;
        grid[r][c] = v;
        /* check constraints as we go rather than only at the end -
           an inequality broken at cell 3 makes every arrangement of
           the remaining cells pointless to explore */
        if (!violates(grid, n, cons)) solve(pos + 1);
        grid[r][c] = 0;
        if (found >= limit) return;
      }
    })(0);
    return found;
  }

  function solve(clues, cons, n) {
    const grid = clues.map((row) => row.slice());
    const ok = (function fill(pos) {
      while (pos < n * n && grid[Math.floor(pos / n)][pos % n] !== 0) pos++;
      if (pos === n * n) return true;
      const r = Math.floor(pos / n), c = pos % n;
      for (let v = 1; v <= n; v++) {
        let clash = false;
        for (let i = 0; i < n; i++) {
          if (grid[r][i] === v || grid[i][c] === v) { clash = true; break; }
        }
        if (clash) continue;
        grid[r][c] = v;
        if (!violates(grid, n, cons) && fill(pos + 1)) return true;
        grid[r][c] = 0;
      }
      return false;
    })(0);
    return ok ? grid : null;
  }

  /** Returns {n, clues, constraints, solution, sizeName}.
      `clues` has 0 for blanks. */
  function generate(sizeName) {
    const n = SIZES[sizeName] || 5;
    for (let attempt = 0; attempt < 40; attempt++) {
      const solution = generateSolved(n);
      if (!solution) continue;

      /* Start from a generous set of signs and a few given digits, then
         strip both back. Starting sparse and adding would mean
         re-testing uniqueness from scratch each time; starting full and
         removing lets each removal be checked in isolation. */
      let cons = shuffled(allConstraints(solution, n))
        .slice(0, Math.max(n, Math.round(n * n * 0.55)));
      const clues = solution.map((row) => row.slice());

      /* not unique even with everything given would mean something is
         wrong with the constraint set - bail to a fresh attempt */
      if (countSolutions(clues, cons, n, 2) !== 1) continue;

      /* remove digits first: a Futoshiki is more interesting when most
         of the information comes from the signs */
      for (const pos of shuffled([...Array(n * n).keys()])) {
        const r = Math.floor(pos / n), c = pos % n;
        const backup = clues[r][c];
        if (!backup) continue;
        clues[r][c] = 0;
        if (countSolutions(clues, cons, n, 2) !== 1) clues[r][c] = backup;
      }

      /* then thin the signs, keeping only those still doing work */
      for (const con of shuffled(cons.slice())) {
        const without = cons.filter((x) => key(x) !== key(con));
        if (countSolutions(clues, without, n, 2) === 1) cons = without;
      }

      const givens = clues.flat().filter(Boolean).length;
      /* a puzzle that ended up as nothing but signs and no digits is
         valid but unusually hard to start; accept it only at the
         smallest size where it's still approachable */
      if (!givens && n > 4) continue;

      return {n, clues, constraints: cons, solution,
              sizeName: sizeName || "medium",
              givens, signs: cons.length};
    }
    return null;
  }

  /** The sign between two adjacent cells, or null. Looked up by the UI
      when drawing the gaps between cells. */
  function signAt(puzzle, r, c, dir) {
    const con = puzzle.constraints.find((x) =>
      x.r === r && x.c === c && x.dir === dir);
    return con ? con.sign : null;
  }

  /** Cells that clash right now — a repeat in a row or column, or a
      broken inequality. Returns a Set of "r,c". */
  function conflicts(puzzle, grid) {
    const n = puzzle.n;
    const bad = new Set();
    for (let r = 0; r < n; r++) {
      const seen = new Map();
      for (let c = 0; c < n; c++) {
        const v = grid[r][c];
        if (!v) continue;
        if (seen.has(v)) { bad.add(`${r},${c}`); bad.add(`${r},${seen.get(v)}`); }
        else seen.set(v, c);
      }
    }
    for (let c = 0; c < n; c++) {
      const seen = new Map();
      for (let r = 0; r < n; r++) {
        const v = grid[r][c];
        if (!v) continue;
        if (seen.has(v)) { bad.add(`${r},${c}`); bad.add(`${seen.get(v)},${c}`); }
        else seen.set(v, r);
      }
    }
    for (const con of puzzle.constraints) {
      const a = grid[con.r][con.c];
      const b = con.dir === "h" ? grid[con.r][con.c + 1]
                                : grid[con.r + 1][con.c];
      if (!a || !b) continue;
      if (con.sign === "<" ? !(a < b) : !(a > b)) {
        bad.add(`${con.r},${con.c}`);
        bad.add(con.dir === "h" ? `${con.r},${con.c + 1}`
                                : `${con.r + 1},${con.c}`);
      }
    }
    return bad;
  }

  function isComplete(puzzle, grid) {
    for (let r = 0; r < puzzle.n; r++) {
      for (let c = 0; c < puzzle.n; c++) if (!grid[r][c]) return false;
    }
    return conflicts(puzzle, grid).size === 0;
  }

  root.Futoshiki = {generate, solve, countSolutions, conflicts, isComplete,
                    signAt, generateSolved, allConstraints, SIZES};
})(CRG);

