/* ---- games/nonogram.js ---- */
/* ==========================================================================
   Nonogram (Picross) and the Sliding Puzzle.
   ==========================================================================
   Grouped because both have a real generator trap that's easy to miss:

   - A nonogram built from a random picture very often has MULTIPLE
     solutions, which means it can't be reasoned out, only guessed.
     Same failure that sank the Kakuro attempt. Here it's genuinely
     tractable: draw the picture, derive the clues from it, then run a
     real solver to confirm exactly one solution exists.

   - HALF of all sliding-puzzle arrangements are mathematically
     IMPOSSIBLE to solve. Shuffling tiles randomly gives you a 50%
     chance of handing someone a puzzle they can never finish. The
     only safe way is to scramble by making legal moves from a solved
     board, which is what happens below.
   ========================================================================== */
(function (root) {
  "use strict";

  const shuffled = (arr) => {
    const a = arr.slice();
    for (let i = a.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
  };

  /* ================================================= NONOGRAM ========= */
  const Nonogram = {
    SIZES: {small: 5, medium: 10, large: 15},

    /** The clue numbers for one line: the lengths of each run of
        filled cells, in order. An empty line is [0] by convention. */
    clueFor(line) {
      const out = [];
      let run = 0;
      for (const v of line) {
        if (v) run++;
        else if (run) { out.push(run); run = 0; }
      }
      if (run) out.push(run);
      return out.length ? out : [0];
    },

    /** Every possible arrangement of a line matching `clue`.
        Used by the solver; capped because a long, loose line has a
        genuinely huge number of arrangements and we only ever need to
        know whether a contradiction exists. */
    linePossibilities(clue, len, cap) {
      cap = cap || 20000;
      const out = [];
      if (clue.length === 1 && clue[0] === 0) return [new Array(len).fill(0)];
      (function place(idx, pos, acc) {
        if (out.length >= cap) return;
        if (idx === clue.length) {
          out.push(acc.concat(new Array(len - acc.length).fill(0)));
          return;
        }
        const need = clue.slice(idx).reduce((a, b) => a + b, 0)
          + (clue.length - idx - 1);
        for (let s = pos; s <= len - need; s++) {
          const next = acc.concat(
            new Array(s - acc.length).fill(0),
            new Array(clue[idx]).fill(1));
          /* a gap of at least one after every block except the last */
          place(idx + 1, s + clue[idx] + 1,
            idx === clue.length - 1 ? next : next.concat([0]));
          if (out.length >= cap) return;
        }
      })(0, 0, []);
      return out;
    },

    /** Counts solutions up to `limit` by constraint propagation plus
        search. Only ever asked "is there more than one?", so it stops
        the moment it finds a second. */
    countSolutions(rowClues, colClues, size, limit) {
      limit = limit || 2;
      const rowOpts = rowClues.map((c) =>
        Nonogram.linePossibilities(c, size));
      /* a line with too many possibilities to enumerate means this
         puzzle is too loose to verify cheaply - treat as ambiguous
         and let the generator try a different picture */
      if (rowOpts.some((o) => o.length === 0 || o.length >= 20000)) return 99;

      let found = 0;
      const grid = [];
      (function pick(r) {
        if (found >= limit) return;
        if (r === size) {
          for (let c = 0; c < size; c++) {
            const col = grid.map((row) => row[c]);
            if (Nonogram.clueFor(col).join(",") !== colClues[c].join(",")) return;
          }
          found++;
          return;
        }
        for (const opt of rowOpts[r]) {
          grid[r] = opt;
          /* prune early: if the partial columns already can't match
             their clues, abandon this branch rather than filling in
             every remaining row first */
          let ok = true;
          for (let c = 0; c < size && ok; c++) {
            const partial = grid.slice(0, r + 1).map((row) => row[c]);
            const got = Nonogram.clueFor(partial).filter((x) => x);
            const want = colClues[c].filter((x) => x);
            if (got.length > want.length) { ok = false; break; }
            for (let i = 0; i < got.length - 1; i++) {
              if (got[i] !== want[i]) { ok = false; break; }
            }
            if (ok && got.length) {
              const last = got[got.length - 1];
              if (last > want[got.length - 1]) ok = false;
            }
          }
          if (ok) pick(r + 1);
          if (found >= limit) return;
        }
        grid.length = r;
      })(0);
      return found;
    },

    /** Returns {size, rowClues, colClues, solution} with exactly one
        solution guaranteed. */
    generate(sizeName) {
      const size = Nonogram.SIZES[sizeName] || 10;
      for (let attempt = 0; attempt < 80; attempt++) {
        /* density around 55% gives pictures that are dense enough to
           be constrained (and so uniquely solvable) but still look
           like a shape rather than a solid block */
        const solution = [];
        for (let r = 0; r < size; r++) {
          const row = [];
          for (let c = 0; c < size; c++) row.push(Math.random() < 0.55 ? 1 : 0);
          solution.push(row);
        }
        const rowClues = solution.map((row) => Nonogram.clueFor(row));
        const colClues = [];
        for (let c = 0; c < size; c++) {
          colClues.push(Nonogram.clueFor(solution.map((row) => row[c])));
        }
        if (Nonogram.countSolutions(rowClues, colClues, size, 2) === 1) {
          return {size, rowClues, colClues, solution,
                  sizeName: sizeName || "medium"};
        }
      }
      return null;
    },

    /** Is the player's grid the solution? Only filled cells matter;
        a cell marked "definitely empty" is a note to self, not an
        answer, so it's ignored here. */
    isSolved(puzzle, marks) {
      for (let r = 0; r < puzzle.size; r++) {
        for (let c = 0; c < puzzle.size; c++) {
          const filled = marks[r][c] === 1;
          if (filled !== (puzzle.solution[r][c] === 1)) return false;
        }
      }
      return true;
    },
  };

  /* ============================================ SLIDING PUZZLE ======== */
  const Sliding = {
    SIZES: {three: 3, four: 4, five: 5},

    /** A solved board: 1..n*n-1 then 0 for the blank. */
    solved(n) {
      const t = [];
      for (let i = 1; i < n * n; i++) t.push(i);
      t.push(0);
      return t;
    },

    blankIndex: (tiles) => tiles.indexOf(0),

    /** The indices the blank could legally swap with. */
    moves(tiles, n) {
      const b = Sliding.blankIndex(tiles);
      const r = Math.floor(b / n), c = b % n;
      const out = [];
      if (r > 0) out.push(b - n);
      if (r < n - 1) out.push(b + n);
      if (c > 0) out.push(b - 1);
      if (c < n - 1) out.push(b + 1);
      return out;
    },

    /** Slides the tile at `i` into the blank, if they're adjacent. */
    move(state, i) {
      if (state.won) return false;
      if (!Sliding.moves(state.tiles, state.n).includes(i)) return false;
      const b = Sliding.blankIndex(state.tiles);
      [state.tiles[b], state.tiles[i]] = [state.tiles[i], state.tiles[b]];
      state.moves++;
      state.won = Sliding.isSolved(state.tiles);
      return true;
    },

    isSolved(tiles) {
      for (let i = 0; i < tiles.length - 1; i++) {
        if (tiles[i] !== i + 1) return false;
      }
      return tiles[tiles.length - 1] === 0;
    },

    /** Scrambles by making legal moves from solved.

        THE IMPORTANT BIT: exactly half of all tile arrangements are
        unreachable from the solved state — mathematically impossible
        to solve, not merely hard. Shuffling the tiles randomly would
        hand the player an impossible board half the time, with no way
        for them to know. Walking backwards from solved can only ever
        produce reachable positions, so every puzzle is guaranteed
        solvable by construction. */
    create(sizeName) {
      const n = Sliding.SIZES[sizeName] || 4;
      const state = {n, tiles: Sliding.solved(n), moves: 0, won: false,
                     sizeName: sizeName || "four"};
      let last = -1;
      const steps = n * n * 40;
      for (let i = 0; i < steps; i++) {
        const opts = Sliding.moves(state.tiles, n).filter((m) => m !== last);
        const pick = opts[Math.floor(Math.random() * opts.length)];
        last = Sliding.blankIndex(state.tiles);
        const b = last;
        [state.tiles[b], state.tiles[pick]] = [state.tiles[pick], state.tiles[b]];
      }
      state.moves = 0;
      /* a scramble can legitimately land back on solved; nudge it
         rather than opening an already-finished puzzle */
      if (Sliding.isSolved(state.tiles)) return Sliding.create(sizeName);
      state.won = false;
      return state;
    },
  };

  /* ================================================== JIGSAW ========== */
  /* v2 — Cam: "have normal puzzles as well where you click to change a
     pieces position."

     Genuinely a different game from the sliding puzzle despite looking
     similar: there's no blank, and ANY two pieces swap by tapping one
     then the other. That removes the sliding puzzle's parity
     constraint entirely — every arrangement is reachable here, so a
     plain shuffle is safe in a way it never is for sliding. */
  const Jigsaw = {
    SIZES: {three: 3, four: 4, five: 5, six: 6},

    create(sizeName) {
      const n = Jigsaw.SIZES[sizeName] || 4;
      const order = [];
      for (let i = 0; i < n * n; i++) order.push(i);
      for (let i = order.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [order[i], order[j]] = [order[j], order[i]];
      }
      const state = {n, order, moves: 0, won: false, selected: null,
                     sizeName: sizeName || "four"};
      /* a shuffle can land on solved - don't open an already-finished
         puzzle */
      if (Jigsaw.isSolved(state)) return Jigsaw.create(sizeName);
      return state;
    },

    /** Tap one piece, then another, to swap them. */
    select(state, i) {
      if (state.won) return "none";
      if (state.selected === null) { state.selected = i; return "picked"; }
      if (state.selected === i) { state.selected = null; return "cleared"; }
      const a = state.selected;
      [state.order[a], state.order[i]] = [state.order[i], state.order[a]];
      state.selected = null;
      state.moves++;
      state.won = Jigsaw.isSolved(state);
      return "swapped";
    },

    isSolved: (state) => state.order.every((v, i) => v === i),

    /** How many pieces are already home — a genuinely useful progress
        signal on a photo, where "nearly right" is hard to eyeball. */
    correct: (state) => state.order.filter((v, i) => v === i).length,
  };

  root.Nonogram = Nonogram;
  root.Sliding = Sliding;
  root.Jigsaw = Jigsaw;
})(CRG);

