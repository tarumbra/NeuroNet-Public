function newSudoku(difficulty) {
  const p = Sudoku.generate(difficulty);
  sudokuState = {
    grid: p.puzzle.slice(),
    given: p.puzzle.map((v) => v !== 0),
    solution: p.solution,
    difficulty: p.difficulty,
    selected: -1,
    won: false,
  };
  startTimer(() => { const el = $("sd-time"); if (el) el.textContent = fmtTime(elapsed); });
  render();
}

function sudokuEnter(n) {
  const st = sudokuState;
  if (!st || st.selected < 0 || st.won) return;
  if (st.given[st.selected]) return;
  st.grid[st.selected] = n;
  if (Sudoku.isComplete(st.grid)) {
    st.won = true;
    stopTimer();
    recordResult("sudoku", {won: true, time: elapsed,
      difficulty: st.difficulty});
    toast("Solved!", "good");
  }
  render();
}

