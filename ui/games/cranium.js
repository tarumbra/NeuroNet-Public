/* v3 — Cam: "Add a more detailed stats list, where i can get a break
   down of how many of the games played were on specific difficulties...
   Also have the total amount of time played on a specific game, the
   longest attempt, the quickest attempt and the average attempt."

   THE MODEL CHANGE THAT MAKES THIS POSSIBLE. The old stats were
   running totals only — plays, wins, and a single best. Totals can't
   be un-summed: there is genuinely no way to recover "how many were on
   Hard" or "what was the average" from a number that has already been
   added up. So every finished game is now stored as its own small
   record, and every figure on the stats page is derived from those.

   A session is deliberately tiny — {won, difficulty, time, moves,
   score, at} — because there will be thousands of them over time and
   they all live in one JSON file.

   Old aggregate stats are migrated rather than thrown away: they can't
   be broken down by difficulty (that detail was never recorded), but
   the play and win counts Cam already has are real and are kept. */

const MAX_SESSIONS = 2000;   // per game; far beyond real use, but a
                             // hard ceiling stops the file growing
                             // without limit over years

function sessionsFor(key) {
  const s = data.stats[key];
  if (!s) return [];
  return Array.isArray(s.sessions) ? s.sessions : [];
}

/** Legacy totals that predate session tracking, if any. Kept separate
    so they can be shown honestly as "before detailed tracking". */
function legacyFor(key) {
  const s = data.stats[key];
  if (!s || !s.legacy) return null;
  return s.legacy;
}

function statsFor(key) {
  const sess = sessionsFor(key);
  const legacy = legacyFor(key);
  const wins = sess.filter((x) => x.won);
  const times = wins.map((x) => x.time).filter(Number.isFinite);
  const moves = wins.map((x) => x.moves).filter(Number.isFinite);
  const scores = sess.map((x) => x.score).filter(Number.isFinite);
  /* total time counts EVERY attempt, won or lost - Cam asked for "the
     total amount of time played", and a lost game was still played */
  const allTimes = sess.map((x) => x.time).filter(Number.isFinite);
  return {
    plays: sess.length + (legacy ? legacy.plays : 0),
    wins: wins.length + (legacy ? legacy.wins : 0),
    sessionPlays: sess.length,
    bestTime: times.length ? Math.min(...times) : null,
    worstTime: times.length ? Math.max(...times) : null,
    avgTime: times.length
      ? Math.round(times.reduce((a, b) => a + b, 0) / times.length) : null,
    totalTime: allTimes.reduce((a, b) => a + b, 0),
    bestMoves: moves.length ? Math.min(...moves) : null,
    worstMoves: moves.length ? Math.max(...moves) : null,
    avgMoves: moves.length
      ? Math.round(moves.reduce((a, b) => a + b, 0) / moves.length) : null,
    bestScore: scores.length ? Math.max(...scores) : null,
    legacy,
  };
}

/** The same figures, but only for sessions matching one difficulty. */
function statsForDifficulty(key, difficulty) {
  const sess = sessionsFor(key).filter((x) => (x.difficulty || "\u2014") === difficulty);
  const wins = sess.filter((x) => x.won);
  const times = wins.map((x) => x.time).filter(Number.isFinite);
  const moves = wins.map((x) => x.moves).filter(Number.isFinite);
  const allTimes = sess.map((x) => x.time).filter(Number.isFinite);
  return {
    difficulty, plays: sess.length, wins: wins.length,
    bestTime: times.length ? Math.min(...times) : null,
    worstTime: times.length ? Math.max(...times) : null,
    avgTime: times.length
      ? Math.round(times.reduce((a, b) => a + b, 0) / times.length) : null,
    totalTime: allTimes.reduce((a, b) => a + b, 0),
    bestMoves: moves.length ? Math.min(...moves) : null,
    avgMoves: moves.length
      ? Math.round(moves.reduce((a, b) => a + b, 0) / moves.length) : null,
  };
}

/** Every difficulty a game has actually been played on, most-played
    first. Derived from real sessions rather than a fixed list, so a
    difficulty Cam has never touched doesn't clutter the page. */
function difficultiesFor(key) {
  const counts = new Map();
  for (const s of sessionsFor(key)) {
    const d = s.difficulty || "\u2014";
    counts.set(d, (counts.get(d) || 0) + 1);
  }
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([d]) => d);
}

async function recordResult(key, {won, time, score, moves, difficulty}) {
  const entry = data.stats[key] || {};
  if (!Array.isArray(entry.sessions)) {
    /* first run after the upgrade: fold any old running totals into a
       legacy record rather than discarding real history */
    if (entry.plays) {
      entry.legacy = {plays: entry.plays, wins: entry.wins || 0,
                       bestTime: entry.bestTime ?? null,
                       bestScore: entry.bestScore ?? null,
                       bestMoves: entry.bestMoves ?? null};
    }
    entry.sessions = [];
    delete entry.plays; delete entry.wins;
    delete entry.bestTime; delete entry.bestScore; delete entry.bestMoves;
  }
  const rec = {won: !!won, at: new Date().toISOString()};
  if (difficulty) rec.difficulty = String(difficulty);
  if (Number.isFinite(time)) rec.time = Math.round(time);
  if (Number.isFinite(moves)) rec.moves = moves;
  if (Number.isFinite(score)) rec.score = score;
  entry.sessions.push(rec);
  if (entry.sessions.length > MAX_SESSIONS) {
    entry.sessions = entry.sessions.slice(-MAX_SESSIONS);
  }
  data.stats[key] = entry;
  await CR.Store.saveData(data);
}

function bestLabel(g) {
  const s = statsFor(g.key);
  if (g.scoreKind === "time" && s.bestTime !== null) return "Best " + fmtTime(s.bestTime);
  if (g.scoreKind === "score" && s.bestScore !== null) return "Best " + s.bestScore;
  if (g.scoreKind === "moves" && s.bestMoves !== null) return "Best " + s.bestMoves + " moves";
  return s.plays ? `${s.plays} played` : "";
}

/* -------------------------------------------------------------- zoom --- */
/* v3 — Cam: "Please have a UI zoom feature for Cranium."

   Implemented by scaling the root font-size, NOT with a CSS transform.
   That matters: a transform would scale the whole page as a flat
   image, blurring text and leaving the layout thinking it was still
   the old size (so scrollbars and click targets drift out of place).
   Changing the root font-size makes the browser genuinely re-lay-out
   at the new scale, so everything stays crisp and correctly
   positioned.

   For that to work, sizes have to be relative. Most of this app's
   boards are specified in px (a 54px Sudoku cell, a 78px light), so
   those get scaled directly through a CSS variable the board rules
   multiply by. See --z in shared.css. */
const ZOOM_STEPS = [0.8, 0.9, 1, 1.1, 1.25, 1.4, 1.6];
let zoomIndex = 2;          // 1.0 by default

function zoomLevel() { return ZOOM_STEPS[zoomIndex]; }

function applyZoom() {
  const z = zoomLevel();
  /* SCOPED TO CRANIUM. This used to set --z and the base font size on the
     PAGE, which scaled the whole app: Cam opened Games, the sidebar, the
     bars and every other tool grew, and Settings showed nothing changed
     because neither Text size nor UI scale had been touched. It also left
     the page that size after leaving Games, and fought Text size, which
     sets the same base font.

     Now it sits on Cranium's own shell. The game boards still size
     themselves from --z (50 rules in cranium.css do), and Cranium's text
     multiplies by it there -- see "calc(... * var(--z, 1))" in that file. */
  const shell = document.getElementById("cr-shell");
  if (!shell) return;          // no shell, nothing to zoom -- and never the page
  shell.style.setProperty("--z", z);
  const label = $("cr-zoom-level");
  if (label) label.textContent = Math.round(z * 100) + "%";
}

async function setZoom(index) {
  const before = zoomIndex;
  zoomIndex = Math.max(0, Math.min(ZOOM_STEPS.length - 1, index));
  if (zoomIndex === before) return;      // already at the end of the range
  applyZoom();
  /* the sliding puzzle bakes its tile size in at render time (it
     divides a fixed board width by the grid), so unlike every other
     board it can't pick up a zoom change from CSS alone - re-render
     the current view so it redraws at the new scale */
  /* Colour by Numbers draws on a canvas, so it too has to redraw to grow */
  if (view === "sliding" || view === "colourbn") render();
  await CR.Store.setPrefs({zoom: zoomIndex});
}

function wireZoom() {
  const out = $("cr-zoom-out"), inn = $("cr-zoom-in");
  if (out) out.onclick = () => setZoom(zoomIndex - 1);
  if (inn) inn.onclick = () => setZoom(zoomIndex + 1);
  /* Ctrl+= / Ctrl+- / Ctrl+0, the shortcuts people already expect from
     every browser and editor. Ctrl is required so a bare "-" typed
     into a word-search list or a book name isn't swallowed. */
  window.addEventListener("keydown", (e) => {
    if (!e.ctrlKey || e.altKey || e.metaKey) return;
    /* only while a Cranium screen is on -- see the note in
       build_games.py about this fighting the host */
    const shell = document.getElementById("cr-shell");
    if (!shell || shell.hidden) return;
    if (e.key === "=" || e.key === "+") { e.preventDefault(); setZoom(zoomIndex + 1); }
    else if (e.key === "-" || e.key === "_") { e.preventDefault(); setZoom(zoomIndex - 1); }
    else if (e.key === "0") { e.preventDefault(); setZoom(2); }
  });
}

