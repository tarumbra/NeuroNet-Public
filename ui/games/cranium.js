/** Which digit sets can make a clue. Genuinely the main solving aid in
    Kakuro — knowing that 3-in-2 can only be {1,2} is most of the game,
    and looking it up on paper is tedious. */
function kakComboDialog(p, r, c) {
  const clue = p.clues[r][c];
  if (!clue) return;
  const parts = [];
  for (const [dir, label] of [["right", "Across"], ["down", "Down"]]) {
    if (!clue[dir]) continue;
    const run = p.runs.find((x) =>
      x.dir === (dir === "right" ? "h" : "v")
      && x.cells[0][0] === (dir === "right" ? r : r + 1)
      && x.cells[0][1] === (dir === "right" ? c + 1 : c));
    if (!run) continue;
    const list = Kakuro.combosFor(run.cells.length, clue[dir]);
    parts.push(`
      <div style="margin-bottom:14px">
        <div class="section-h" style="margin-top:0">${label} \u2014
          ${clue[dir]} in ${run.cells.length}
          <span class="stamp">${list.length} way${list.length === 1 ? "" : "s"}</span>
        </div>
        <div class="kk-combos">
          ${list.map((set) => `<span class="kk-combo">${set.join(" ")}</span>`)
            .join("")}
        </div>
      </div>`);
  }
  if (!parts.length) return;
  const d = openDlg("Possible combinations", parts.join(""));
  d.btn("Close", "btn-primary", d.close);
}

