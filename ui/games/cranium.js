let viewingBook = null;

function renderBooks(page) {
  if (viewingBook) { renderBookDetail(page); return; }
  const books = booksAll();
  page.innerHTML = `
    <h2 class="page-h">Puzzle books</h2>
    <p class="page-sub">Collect puzzles as you generate them, then print
      the whole book at once.</p>
    <button class="btn btn-primary" id="bk-add" style="margin-bottom:18px">
      + New book</button>
    ${books.length ? `
      <div class="bk-grid">
        ${books.map((b) => `
          <div class="bk-card" data-open="${escA(b.id)}">
            ${bookCoverHtml(b, true)}
            <div class="bk-card-meta">
              <b>${esc(b.name)}</b>
              <span class="stamp">${b.puzzles.length} puzzle${
                b.puzzles.length === 1 ? "" : "s"}</span>
            </div>
          </div>`).join("")}
      </div>`
      : `<div class="empty">No books yet.<br>Make one here, or hit
           <b>Add to book</b> on any Sudoku, Word Search, Nonogram, Futoshiki or Kakuro you've generated.</div>`}`;

  page.querySelector("#bk-add").onclick = async () => {
    const name = await promptBookName();
    if (!name) return;
    await createBook(name);
    render();
    toast("Book created.", "good");
  };
  page.querySelectorAll("[data-open]").forEach((el) =>
    el.addEventListener("click", () => { viewingBook = el.dataset.open; render(); }));
}

function promptBookName(initial) {
  return new Promise((resolve) => {
    const d = openDlg(initial ? "Rename book" : "New book", `
      <label class="label" style="margin-top:0">Name</label>
      <input class="input" id="bk-name" style="width:100%"
             value="${escA(initial || "")}" placeholder="Holiday puzzles">`);
    d.btn("Cancel", "btn-quiet", () => { d.close(); resolve(null); });
    d.btn("Save", "btn-primary", () => {
      const v = d.body.querySelector("#bk-name").value.trim();
      d.close();
      resolve(v || null);
    });
    setTimeout(() => d.body.querySelector("#bk-name").focus(), 50);
  });
}

function renderBookDetail(page) {
  const b = bookById(viewingBook);
  if (!b) { viewingBook = null; render(); return; }

  /* group by game so a mixed book reads as a contents page rather than
     an undifferentiated list */
  const byGame = new Map();
  b.puzzles.forEach((p, i) => {
    const key = p.game;
    if (!byGame.has(key)) byGame.set(key, []);
    byGame.get(key).push({p, i});
  });

  page.innerHTML = `
    <div class="game-bar">
      <button class="btn btn-quiet btn-sm" id="bk-back">${ic("i-back")}
        All books</button>
      <span class="stat-pill">Puzzles <b>${b.puzzles.length}</b></span>
      <span class="spacer"></span>
      <button class="btn btn-sm" id="bk-cover">Cover</button>
      <button class="btn btn-sm" id="bk-rename">Rename</button>
      <button class="btn btn-sm btn-danger" id="bk-delete">Delete book</button>
      <button class="btn btn-primary btn-sm" id="bk-print"
        ${b.puzzles.length ? "" : "disabled"}>${ic("i-print")} Print book</button>
    </div>

    <div class="bk-detail">
      ${bookCoverHtml(b, false)}
      <div class="bk-contents">
        ${b.puzzles.length ? [...byGame.entries()].map(([game, items]) => `
          <div class="bk-group">
            <div class="section-h" style="margin-top:0">
              ${esc(BOOKABLE[game] ? BOOKABLE[game].name : game)}
              <span class="stamp">${items.length}</span>
            </div>
            ${items.map(({p, i}) => `
              <div class="bk-row">
                <span>${esc(BOOKABLE[p.game]
                  ? BOOKABLE[p.game].label(p.data) : p.game)}</span>
                <button class="btn btn-quiet btn-sm" data-rm="${i}"
                  title="Remove">&#10006;</button>
              </div>`).join("")}
          </div>`).join("")
          : `<div class="empty">Nothing in this book yet.<br>
               Generate a puzzle and hit <b>Add to book</b>.</div>`}
      </div>
    </div>`;

  page.querySelector("#bk-back").onclick = () => { viewingBook = null; render(); };
  page.querySelector("#bk-cover").onclick = () => coverPickerDialog(b);
  page.querySelector("#bk-rename").onclick = async () => {
    const name = await promptBookName(b.name);
    if (!name) return;
    b.name = name;
    await CR.Store.saveData(data);
    render();
  };
  page.querySelector("#bk-delete").onclick = async () => {
    const ok = await confirmDlg({title: "Delete this book?",
      body: `"${b.name}" and its ${b.puzzles.length} puzzle${
        b.puzzles.length === 1 ? "" : "s"} will be gone. This can't be undone.`,
      yes: "Delete"});
    if (!ok) return;
    data.books = booksAll().filter((x) => x.id !== b.id);
    await CR.Store.saveData(data);
    viewingBook = null;
    render();
    toast("Book deleted.");
  };
  page.querySelector("#bk-print").onclick = () => printBook(b);
  page.querySelectorAll("[data-rm]").forEach((btn) =>
    btn.addEventListener("click", async () => {
      b.puzzles.splice(+btn.dataset.rm, 1);
      await CR.Store.saveData(data);
      render();
    }));
}

