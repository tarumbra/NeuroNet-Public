async function cbnMake(sizeName) {
  const photo = await pickPuzzlePhoto("Choose a photo to paint by numbers", 480);
  if (!photo) return null;
  const n = ColourByNumbers.SIZES[sizeName], k = ColourByNumbers.COLOURS[sizeName];
  const img = await new Promise((res, rej) => {
    const im = new Image(); im.onload = () => res(im); im.onerror = rej; im.src = photo.url;
  });
  const cv = document.createElement("canvas");
  cv.width = cv.height = n;
  const ctx = cv.getContext("2d");
  ctx.imageSmoothingQuality = "high";
  ctx.drawImage(img, 0, 0, n, n);
  const st = ColourByNumbers.fromPixels(ctx.getImageData(0, 0, n, n).data, n, k);
  st.sizeName = sizeName;
  st.name = photo.name;
  return st;
}

/* Cam (14 Nov 2026): "once completed they should get added to the pixel art
   creator app as a project. Then i can go alter them in there later for
   practice or redesign." The finished grid becomes a Pixel art sprite (one
   pixel per cell, the picture's own colours as its palette), saved into
   Assets -> In progress like any sprite. */
async function cbnToPixel(s) {
  const C = window.PixelCore;
  if (!C || !window.SS || !SS.Store) return null;
  const name = `Colour by Numbers: ${s.name || "Picture"}`;
  const p = C.newProject(s.n, s.n, name);
  const img = p.cels[p.layers[0].id][0];
  s.cells.forEach((ci, i) => C.set(img, s.n, s.n, i % s.n, Math.floor(i / s.n), C.hexToRgba(s.palette[ci])));
  p.palette = {name: `${s.name || "Picture"} colours`, colours: s.palette.slice()};
  const k = Math.max(1, Math.floor(256 / s.n));
  const preview = C.pngDataUrl(C.scaleUp(C.composite(p, 0), s.n, s.n, k), s.n * k, s.n * k);
  try {
    const r = await SS.Store.call("asset_add", ["other", name, preview, C.serialise(p), [s.n, s.n], "wip"], "Saving to Pixel art");
    if (r && r.ok) {
      if (SS.AssetStore && SS.AssetStore.forget) SS.AssetStore.forget(r.id);
      return r.id;
    }
  } catch (e) { /* the puzzle is still won; only the copy failed */ }
  return null;
}

