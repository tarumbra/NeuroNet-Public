/* ==========================================================================
   Kakuro — generator and solver. SECOND ATTEMPT.
   ==========================================================================
   WHY THE FIRST ATTEMPT FAILED, because it shaped this one. That version
   laid out random walls, filled the white cells with any digits that fit,
   then derived each clue from whatever total came out. Measured result:
   ZERO uniquely-solvable puzzles across every grid size, with solution
   counting taking 7.6 seconds a go. The cause was structural — a run of
   4 cells summing to 22 has dozens of valid digit combinations, so a
   grid full of such runs is hopelessly ambiguous.

   WHAT'S DIFFERENT NOW. Real Kakuro leans on runs whose (length, sum)
   pair admits very few digit combinations — a 2-cell run summing to 3
   can ONLY be {1,2}; a 3-cell run summing to 6 can only be {1,2,3}.
   COMBO_COUNT below is computed up front, and the generator deliberately
   prefers layouts and totals that are tightly constrained. Uniqueness
   is still verified at the end and a failure still throws the puzzle
   away, but now the candidates being tested are ones likely to pass
   rather than near-certain to fail.

   Also: short runs. Runs are capped at 4 cells (5 at the largest size),
   because ambiguity grows sharply with run length and long runs were a
   large part of what sank the first attempt.
   ========================================================================== */
(function (root) {
  "use strict";

  const WALL = -1;

  /* minWhite is a real quality floor, added after measuring: without
     it the generator happily returned puzzles with as few as FOUR
     white cells, which is technically a valid unique Kakuro and
     completely pointless to solve. A layout that prunes down below the
     floor is discarded and a fresh one tried. */
  /* minWhite is a real quality floor, added after measuring: without it
     the generator happily returned puzzles with as few as FOUR white
     cells — technically a valid unique Kakuro, and completely
     pointless to solve.

     The numbers are tuned to what each grid can actually deliver.
     Measured layout medians are roughly 10 / 25 / 41 white cells for
     7x7 / 9x9 / 11x11, but uniqueness gets harder as a grid grows (more
     runs, more interaction), so the floors sit below those medians.
     Set them at the median and generation starts failing outright —
     which is exactly what happened at the first pass. */
  const SIZES = {
    small:  {rows: 7,  cols: 7,  maxRun: 3, minWhite: 10},
    medium: {rows: 9,  cols: 9,  maxRun: 3, minWhite: 18},
    large:  {rows: 10, cols: 10, maxRun: 3, minWhite: 26},
  };

  const shuffled = (arr) => {
    const a = arr.slice();
    for (let i = a.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
  };

  /* ------------------------------------------------ combination maths --- */
  /** Every set of `len` distinct digits 1-9 adding to `sum`. */
  function combos(len, sum) {
    const out = [];
    (function pick(start, left, rem, acc) {
      if (left === 0) { if (rem === 0) out.push(acc.slice()); return; }
      for (let d = start; d <= 9; d++) {
        if (d > rem) break;
        acc.push(d);
        pick(d + 1, left - 1, rem - d, acc);
        acc.pop();
      }
    })(1, len, sum, []);
    return out;
  }

  /* Precomputed once: how many combinations each (length, sum) allows.
     This table is the whole basis of the new approach — it's what lets
     the generator choose tight totals instead of arbitrary ones. */
  const COMBO_COUNT = {};
  const COMBO_LIST = {};
  for (let len = 1; len <= 9; len++) {
    for (let sum = 1; sum <= 45; sum++) {
      const list = combos(len, sum);
      if (list.length) {
        COMBO_COUNT[`${len}:${sum}`] = list.length;
        COMBO_LIST[`${len}:${sum}`] = list;
      }
    }
  }

  const comboCount = (len, sum) => COMBO_COUNT[`${len}:${sum}`] || 0;

  /** Totals for a run of this length, tightest first. A 2-run prefers
      3, 4, 16, 17 (one combination each) over 9 (four combinations). */
  function tightTotals(len) {
    const out = [];
    for (let sum = 1; sum <= 45; sum++) {
      const n = comboCount(len, sum);
      if (n) out.push({sum, n});
    }
    return out.sort((a, b) => a.n - b.n);
  }

  /* ----------------------------------------------------------- layout --- */
  /** Carves walls into a solid block, then caps run lengths.
      Row 0 and column 0 are always wall, since every run needs a clue
      cell in front of it. */
  function layout(rows, cols, maxRun) {
    const cells = [];
    for (let r = 0; r < rows; r++) {
      const row = [];
      for (let c = 0; c < cols; c++) {
        row.push((r === 0 || c === 0) ? WALL
          : (Math.random() < 0.22 ? WALL : 0));
      }
      cells.push(row);
    }
    /* break any stretch longer than maxRun. Short runs are the single
       biggest lever on whether the finished puzzle is uniquely
       solvable, so this is enforced rather than hoped for. */
    const cut = (get, set, len) => {
      let start = -1;
      for (let i = 1; i <= len; i++) {
        if (i < len && get(i) !== WALL) { if (start < 0) start = i; continue; }
        if (start >= 0 && i - start > maxRun) set(start + maxRun);
        start = (i < len && get(i) !== WALL) ? i : -1;
      }
    };
    for (let r = 1; r < rows; r++) {
      cut((c) => cells[r][c], (c) => { cells[r][c] = WALL; }, cols);
    }
    for (let c = 1; c < cols; c++) {
      cut((r) => cells[r][c], (r) => { cells[r][c] = WALL; }, rows);
    }
    return cells;
  }

  function findRuns(cells) {
    const rows = cells.length, cols = cells[0].length;
    const runs = [];
    for (let r = 0; r < rows; r++) {
      let run = [];
      for (let c = 0; c <= cols; c++) {
        if (c < cols && cells[r][c] !== WALL) { run.push([r, c]); continue; }
        if (run.length >= 2) runs.push({dir: "h", cells: run});
        run = [];
      }
    }
    for (let c = 0; c < cols; c++) {
      let run = [];
      for (let r = 0; r <= rows; r++) {
        if (r < rows && cells[r][c] !== WALL) { run.push([r, c]); continue; }
        if (run.length >= 2) runs.push({dir: "v", cells: run});
        run = [];
      }
    }
    return runs;
  }

  /** Any white cell not in BOTH a horizontal and a vertical run of 2+
      is walled off: a cell constrained in only one direction makes the
      puzzle far weaker and often genuinely ambiguous. */
  function pruneOrphans(cells) {
    let changed = true;
    while (changed) {
      changed = false;
      const runs = findRuns(cells);
      const inH = new Set(), inV = new Set();
      for (const run of runs) {
        for (const [r, c] of run.cells) {
          (run.dir === "h" ? inH : inV).add(r + "," + c);
        }
      }
      for (let r = 0; r < cells.length; r++) {
        for (let c = 0; c < cells[0].length; c++) {
          if (cells[r][c] === WALL) continue;
          const k = r + "," + c;
          if (!inH.has(k) || !inV.has(k)) { cells[r][c] = WALL; changed = true; }
        }
      }
    }
    return cells;
  }

  /* ------------------------------------------------------------- fill --- */
  /** Fills the white cells so no run repeats a digit, PREFERRING
      arrangements whose resulting run totals are tightly constrained.

      This is the real change from the first attempt: rather than taking
      any legal fill and accepting whatever sums fall out, candidate
      digits are ordered so that runs end up on totals with few
      alternative combinations. */
  function fillValues(cells, runs) {
    const white = [];
    for (let r = 0; r < cells.length; r++) {
      for (let c = 0; c < cells[0].length; c++) {
        if (cells[r][c] !== WALL) white.push([r, c]);
      }
    }
    const runsOf = new Map();
    for (const [r, c] of white) runsOf.set(r + "," + c, []);
    for (const run of runs) {
      for (const [r, c] of run.cells) runsOf.get(r + "," + c).push(run);
    }

    const ok = (function place(i) {
      if (i === white.length) return true;
      const [r, c] = white[i];
      const mine = runsOf.get(r + "," + c);

      /* score each candidate by how tight it leaves its runs; try the
         tightest first. A cheap heuristic, but it's what moves the hit
         rate from effectively zero to usable. */
      const cands = [];
      for (const v of shuffled([1, 2, 3, 4, 5, 6, 7, 8, 9])) {
        let clash = false;
        for (const run of mine) {
          for (const [rr, cc] of run.cells) {
            if ((rr !== r || cc !== c) && cells[rr][cc] === v) { clash = true; break; }
          }
          if (clash) break;
        }
        if (clash) continue;
        let score = 0;
        for (const run of mine) {
          let sum = v, blanks = 0;
          for (const [rr, cc] of run.cells) {
            if (rr === r && cc === c) continue;
            const cur = cells[rr][cc];
            if (cur === 0) blanks++; else sum += cur;
          }
          /* once a run is fully determined, prefer a total with fewer
             possible combinations */
          if (blanks === 0) score += comboCount(run.cells.length, sum);
          else score += 3;          // undetermined: neutral
        }
        cands.push({v, score});
      }
      cands.sort((a, b) => a.score - b.score);

      for (const {v} of cands) {
        cells[r][c] = v;
        if (place(i + 1)) return true;
        cells[r][c] = 0;
      }
      return false;
    })(0);
    return ok;
  }

  /* ----------------------------------------------------------- solving --- */
  /** Counts solutions up to `limit`. Uses the combination table to
      prune: a run whose remaining cells can't reach its total, or has
      already overshot, is abandoned immediately. */
  function countSolutions(puzzle, limit) {
    limit = limit || 2;
    const {rows, cols, walls, runs} = puzzle;
    const grid = [];
    for (let r = 0; r < rows; r++) {
      grid.push(new Array(cols).fill(0).map((_, c) => walls[r][c] ? WALL : 0));
    }
    const white = [];
    for (let r = 0; r < rows; r++) {
      for (let c = 0; c < cols; c++) if (!walls[r][c]) white.push([r, c]);
    }
    const runsOf = new Map();
    for (const [r, c] of white) runsOf.set(r + "," + c, []);
    for (const run of runs) {
      for (const [r, c] of run.cells) runsOf.get(r + "," + c).push(run);
    }

    let found = 0;
    (function solve(i) {
      if (found >= limit) return;
      if (i === white.length) { found++; return; }
      const [r, c] = white[i];
      for (let v = 1; v <= 9; v++) {
        let fits = true;
        for (const run of runsOf.get(r + "," + c)) {
          let sum = v, blanks = 0, dup = false;
          for (const [rr, cc] of run.cells) {
            if (rr === r && cc === c) continue;
            const cur = grid[rr][cc];
            if (cur === 0) { blanks++; continue; }
            if (cur === v) { dup = true; break; }
            sum += cur;
          }
          if (dup) { fits = false; break; }
          if (sum > run.sum) { fits = false; break; }
          if (blanks === 0 && sum !== run.sum) { fits = false; break; }
          /* the remaining blanks must be fillable with distinct unused
             digits reaching exactly the shortfall - if no combination
             of that size and total exists, this branch is already dead */
          if (blanks > 0 && !comboCount(blanks, run.sum - sum)) {
            fits = false; break;
          }
        }
        if (!fits) continue;
        grid[r][c] = v;
        solve(i + 1);
        grid[r][c] = 0;
        if (found >= limit) return;
      }
    })(0);
    return found;
  }

  /* -------------------------------------------------------- generating --- */
  /** Returns {rows, cols, walls, clues, runs, solution} or null.
      `walls[r][c]` is true for a black cell; `clues[r][c]` is
      {right, down} where present. */
  function generate(size) {
    const conf = SIZES[size] || SIZES.medium;
    for (let attempt = 0; attempt < 400; attempt++) {
      const cells = pruneOrphans(
        layout(conf.rows, conf.cols, conf.maxRun));
      /* reject a layout that pruned away to almost nothing BEFORE
         spending time filling and solution-counting it */
      const whiteCount = cells.flat().filter((v) => v !== WALL).length;
      if (whiteCount < conf.minWhite) continue;
      const runs = findRuns(cells);
      if (runs.length < 4) continue;
      if (!fillValues(cells, runs)) continue;

      for (const run of runs) {
        run.sum = run.cells.reduce((s, [r, c]) => s + cells[r][c], 0);
      }

      const walls = cells.map((row) => row.map((v) => v === WALL));
      const solution = cells.map((row) => row.slice());

      const clues = [];
      for (let r = 0; r < conf.rows; r++) clues.push(new Array(conf.cols).fill(null));
      let clueOk = true;
      for (const run of runs) {
        const [fr, fc] = run.cells[0];
        const cr = run.dir === "h" ? fr : fr - 1;
        const cc = run.dir === "h" ? fc - 1 : fc;
        if (cr < 0 || cc < 0) { clueOk = false; break; }
        clues[cr][cc] = clues[cr][cc] || {};
        clues[cr][cc][run.dir === "h" ? "right" : "down"] = run.sum;
      }
      if (!clueOk) continue;

      const puzzle = {rows: conf.rows, cols: conf.cols, walls, clues, runs,
                      solution, size: size || "medium"};
      /* the same guarantee every other generator here gives: exactly
         one solution, or it isn't a real puzzle */
      if (countSolutions(puzzle, 2) === 1) return puzzle;
    }
    /* Larger grids genuinely fail more often — more runs interact, so
       more candidate layouts turn out ambiguous. Rather than handing
       back null and showing an error, drop to the next size down and
       try again: a slightly smaller real puzzle is far better than no
       puzzle. Only `small` can return null, and only if the generator
       is truly stuck. */
    const fallback = {large: "medium", medium: "small"}[size];
    if (fallback) return generate(fallback);
    return null;
  }

  /* ---------------------------------------------------------- checking --- */
  function conflicts(puzzle, grid) {
    const bad = new Set();
    for (const run of puzzle.runs) {
      const vals = run.cells.map(([r, c]) => grid[r][c]);
      const seen = new Map();
      vals.forEach((v, i) => {
        if (!v) return;
        if (seen.has(v)) {
          bad.add(run.cells[i].join(","));
          bad.add(run.cells[seen.get(v)].join(","));
        } else seen.set(v, i);
      });
      if (vals.every((v) => v)) {
        if (vals.reduce((a, b) => a + b, 0) !== run.sum) {
          run.cells.forEach(([r, c]) => bad.add(r + "," + c));
        }
      }
    }
    return bad;
  }

  function isComplete(puzzle, grid) {
    for (let r = 0; r < puzzle.rows; r++) {
      for (let c = 0; c < puzzle.cols; c++) {
        if (!puzzle.walls[r][c] && !grid[r][c]) return false;
      }
    }
    return conflicts(puzzle, grid).size === 0;
  }

  /** The possible digit sets for a clue — shown as a hint, and the same
      table the generator and solver both lean on. */
  const combosFor = (len, sum) => COMBO_LIST[`${len}:${sum}`] || [];

  root.Kakuro = {generate, countSolutions, conflicts, isComplete, findRuns,
                 combos, combosFor, comboCount, tightTotals, SIZES, WALL};
})(CRG);

