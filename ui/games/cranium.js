  page.querySelector("#py-new").onclick = () => { stopTimer(); pyState = null; pySel = null; go("pyramid"); };
  page.querySelector("#py-undo").onclick = () => { Pyramid.undo(s); pySel = null; render(); };
  page.querySelector("#py-stock").onclick = () => { pySel = null; Pyramid.deal(s); render(); };
