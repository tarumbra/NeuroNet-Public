/** A duration in a form that reads naturally at any scale - seconds
    for a quick game, hours once a total adds up over months. */
function fmtDuration(sec) {
  if (!Number.isFinite(sec) || sec <= 0) return "\u2014";
  const h = Math.floor(sec / 3600);
  const m = Math.floor((sec % 3600) / 60);
  const s = Math.round(sec % 60);
  if (h) return `${h}h ${m}m`;
  if (m) return `${m}m ${s}s`;
  return `${s}s`;
}

