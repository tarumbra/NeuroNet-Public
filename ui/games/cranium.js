/** Which logo suits this book? Used as the default so most books look
    right without Cam choosing anything: a single-type book gets its own
    emblem, a mixed one gets the brain. */
function suggestedLogo(book) {
  const kinds = new Set(book.puzzles.map((p) => p.game));
  if (kinds.size === 1) {
    const only = [...kinds][0];
    if (COVER_LOGOS[only]) return only;
  }
  return "mixed";
}

const logoFor = (book) => COVER_LOGOS[book.logo] ? book.logo
  : suggestedLogo(book);

