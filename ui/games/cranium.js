/** Every colour covering a cell — a cell can genuinely belong to two
    found words where they cross. */
function wsColorsAt(r, c) {
  const out = [];
  for (const f of wsState.found) {
    if (f.cells.some(([rr, cc]) => rr === r && cc === c)) out.push(f.color);
  }
  return out;
}

function wsCellStyle(r, c) {
  const cols = wsColorsAt(r, c).map((i) => WS_COLORS[i].hex);
  if (!cols.length) return "";
  if (cols.length === 1) return `background:${cols[0]}33;color:${cols[0]}`;
  /* two or more words cross here: show both colours split rather than
     letting one quietly win */
  const stops = cols.map((h, i) =>
    `${h}44 ${(i / cols.length) * 100}% ${((i + 1) / cols.length) * 100}%`);
  return `background:linear-gradient(135deg, ${stops.join(", ")});color:var(--ink)`;
}

