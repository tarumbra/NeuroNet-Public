  function palette(species, colour, skin) {
    var an = ANIMAL_PETS[species + "/" + colour] || (!COLOURS[species] && ANIMAL_SPECIES[species]), pal;
    if (an) pal = MONSTER_ART[an].pal;
    else {
      var sp = COLOURS[species] || COLOURS.cat;
      var c = sp[colour] || sp[Object.keys(sp)[0]];
      pal = { o: INK, b: c.b, l: c.l, p: PINK, e: EYE, w: WHITE, t: TEAR, s: c.b };
    }
    if (!skin) return pal;
    var out = {};
    for (var k in pal) out[k] = skin[k] || pal[k];
    return out;
  }

  function put(rows, x, y, ch) {
    if (y < 0 || y >= rows.length || x < 0 || x >= rows[y].length) return;
    rows[y] = rows[y].substring(0, x) + ch + rows[y].substring(x + 1);
  }

