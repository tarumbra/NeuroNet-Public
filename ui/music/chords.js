/* --------------------------------------------------------------------------
   CH.Store — talks to chords_app.py's own Api.
   -------------------------------------------------------------------------- */
CH.Store = (() => {
  let api = null;   // window.pywebview.api once the bridge is up

  const ready = new Promise((resolve) => {
    if (window.pywebview && window.pywebview.api) {
      api = window.pywebview.api;
      resolve();
      return;
    }
    window.addEventListener("pywebviewready", () => {
      api = window.pywebview.api;
      resolve();
    });
    setTimeout(() => resolve(), 800);
  });

  const isDesktop = () => api !== null;

  return {
    ready,
    isDesktop,

    async readJSON(name) {
      await ready;
      return isDesktop() ? api.music_read_json(name) : null;
    },
    async writeJSON(name, data) {
      await ready;
      return isDesktop() ? api.music_write_json(name, data) : {ok: false};
    },
    /** data: URL for an image, full resolution — use this only where
        Cam actually looks at the picture (the open album's own big
        cover, the top-bar mini-player). */
    async imageURL(name) {
      await ready;
      return isDesktop() ? api.music_image_url(name) : null;
    },
    /** A downscaled, cached copy — for the album shelf and every track
        row's own small art icon, anything scrolled past rather than
        looked at directly. */
    async thumbURL(name, maxEdge) {
      await ready;
      return isDesktop() ? api.music_thumb_url(name, maxEdge) : null;
    },
    /** The key a picture is remembered under. It carries the SIZE as
        well as the file, because the same sleeve is fetched at 96 for a
        track row, 300 for a shelf case and whatever the open album's
        cover measures -- three different pictures of one file, and
        sharing a key would hand a row icon the big one. */
    artKey(name, maxEdge) { return "music:" + name + "@" + (maxEdge || 0); },
    /** thumbURL, remembered.

        Cam: "it lags when i move around the app, especially when loading
        the album sub section found under the music main section."
        Measured: every visit to Music re-fetched every picture from
        scratch -- 400 bridge calls for a 400-track library, 25 more for
        the shelf, each one base64 across a bridge that serialises them.
        Nothing here was cached, so leaving the section and coming back
        paid all of it again.

        SS.Art is the host's one cache and its one gate on how many
        calls are in the air at once, shared with the photo library
        rather than a second copy of it. Falling back to the plain
        fetch keeps this working if a module is ever loaded without the
        host, which is how the tests exercise it. */
    cachedThumbURL(name, maxEdge) {
      if (!name) return Promise.resolve(null);
      if (window.SS && window.SS.Art) {
        return window.SS.Art.get(this.artKey(name, maxEdge),
          () => this.thumbURL(name, maxEdge));
      }
      return this.thumbURL(name, maxEdge);
    },
    async saveImage(name, dataUrl) {
      await ready;
      return isDesktop() ? api.music_save_image(name, dataUrl) : null;
    },
  };
})();

