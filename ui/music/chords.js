  async function removeTrack(page, file) {
    const ok = await CH.confirm({
      title: `Remove “${meta(file).title || file}”?`,
      body: "This clears its title, artist, and album info, and takes " +
            "it out of every playlist and the current queue. The file " +
            "itself stays in your music folder, so it'll still show " +
            "up here under its own filename — tick delete on the next " +
            "screen to actually take it out of your library.",
      yes: "Remove"});
    if (!ok) return;
    let alsoDelete = false;
    /* A second, explicit confirm for the destructive half — deleting the
       real file is never bundled into the same click as de-listing it.
       The ONLY way a track genuinely disappears from the library at
       all: it's built from the real files on disk (see allTracks()
       above), not from this metadata alone. */
    if (CH.Store.isDesktop()) {
      alsoDelete = await CH.confirm({
        title: "Delete the actual file too?",
        body: `This permanently deletes ${file} from your music ` +
              `folder — the only way to actually take it out of your ` +
              `library, since the library is built from what's really ` +
              `on disk. Cancel to keep the file; its title, artist, ` +
              `album info, and playlist memberships are already ` +
              `cleared either way.`,
        yes: "Delete the file", fine: "There's no undo for this."});
    }
    delete store.tracks[file];
    store.playlists.forEach((p) => {
      p.files = (p.files || []).filter((f) => f !== file);
    });
    CH.Player.forgetFile(file);
    save();
    if (CH.Store.isDesktop() && api().chords_remove) {
      try { await api().chords_remove(file, alsoDelete); } catch (e) {}
    }
    await loadAll();
    render();
    CH.toast(alsoDelete ? "Track and file deleted." : "Track removed.");
  }

