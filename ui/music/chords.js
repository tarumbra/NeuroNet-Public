  function pickAndStoreImageLocal(nameHint) {
    return new Promise((resolve) => {
      const inp = document.createElement("input");
      inp.type = "file";
      inp.accept = "image/*";
      inp.onchange = async () => {
        const file = inp.files && inp.files[0];
        if (!file) { resolve(null); return; }
        try {
          const url = await new Promise((res, rej) => {
            const r = new FileReader();
            r.onload = () => res(r.result);
            r.onerror = rej;
            r.readAsDataURL(file);
          });
          const img = await new Promise((res, rej) => {
            const i = new Image();
            i.onload = () => res(i);
            i.onerror = rej;
            i.src = url;
          });
          const scale = Math.min(1, MAX_PHOTO_EDGE
                                 / Math.max(img.width, img.height));
          const canvas = document.createElement("canvas");
          canvas.width = Math.round(img.width * scale);
          canvas.height = Math.round(img.height * scale);
          canvas.getContext("2d").drawImage(img, 0, 0,
                                            canvas.width, canvas.height);
          const isPng = /png$/i.test(file.type);
          const out = canvas.toDataURL(isPng ? "image/png" : "image/jpeg",
                                       0.78);
          const stem = (nameHint || "album").trim().toLowerCase()
            .replace(/[^a-z0-9_-]+/g, "_") || "album";
          resolve(await CH.Store.saveImage(
            stem + (isPng ? ".png" : ".jpg"), out));
        } catch (e) {
          CH.toast("Couldn't read that image.", "error");
          resolve(null);
        }
      };
      inp.click();
    });
  }

