  play(kind, id) {
    const c = CH.tools && CH.tools.chords;
    if (!c) return false;
    if (kind === "album") return c.playAlbumById ? c.playAlbumById(id) : false;
    const p = (c.getPlaylists() || []).find((x) => x.id === id);
    if (!p) return false;
    const tracks = (p.files || []).map((f) => c._test.trackOf(f))
      .filter((t) => t && !t.missing);
    if (!tracks.length) { CH.toast("That playlist is empty.", "error"); return false; }
    CH.Player.playQueue(tracks, 0);
    CH.toast(`Playing \u201C${p.name}\u201D.`);
    return true;
  },
