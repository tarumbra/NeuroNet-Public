/* ---- chords_visualizer.js ---- */
/* ==========================================================================
   CH.Visualizer — a real, audio-reactive visualizer, built SAFE.

   Cam: "Another cool feature will be a visualizer i can have going as
   well. So this way i can open one of the side panels change song
   etc then close it and be back at the visualizer."

   WHY THIS ISN'T A LIVE WEB AUDIO GRAPH TAPPING CH.Player's <audio>:
   Cam's own equaliser feature was removed earlier specifically because
   its Web Audio graph — createMediaElementSource + BiquadFilterNodes
   wired to audioContext.destination — caused real, hard-to-diagnose
   silent-audio bugs on WebKitGTK (a watchdog to detect a silently-
   broken graph, a crossOrigin workaround, a last-resort audio-element
   rebuild — all removed along with it). Once you call
   createMediaElementSource() on an <audio> element, THAT element's own
   native output is permanently rerouted through the Web Audio graph —
   if the graph ever breaks, audio goes silent, with no way back short
   of rebuilding the element. That is too large a risk to reintroduce
   onto the one thing this app must never break.

   So instead: each track's own audio bytes are fetched and decoded
   completely independently, on a throwaway AudioContext that is never
   connected to anything and never touches CH.Player's own <audio>
   element at all. The visualizer reads a real, decoded waveform for
   genuine, data-driven bars — but if the fetch or decode ever fails
   for any reason, playback itself is entirely unaffected, because
   nothing here was ever part of the playback path to begin with. A
   calm, honest fallback animation covers that case instead of a
   blank, broken-looking panel.
   ========================================================================== */
CH.Visualizer = (() => {
  /* 2026-10-02 -- Cam: "I want a different visualiser then the ones we
     currently have, i want a free flowing modern visualiser" (with a picture:
     neon ribbons, a silk mesh, mirrored bars, a dot matrix, a glowing line,
     crossing waves). The drawing is ui/music/nnviz.js -- the SAME file draws
     the desktop Music widget's visualizer, so the two always match.

     Still built SAFE, as before: the track is fetched and decoded on its own
     throwaway AudioContext that is never connected to anything -- CH.Player's
     <audio> is never touched. What's new is what's worked out from it: a
     SPECTRUM -- 32 bands, low to high, 20 times a second, for the whole song
     (an FFT, done once per track, in slices so the page never stalls) --
     instead of one loudness value. Drawn at the playhead. */
  const FPS = 20, NB = 32, N = 1024, CACHE_CAP = 12;

  let el = null, canvas = null, ctx2d = null, rafId = null, asleep = null;
  let resizeObserver = null, playerUnsub = null;
  const vizCache = {};                  // gradients kept between frames (nnviz.js)
  const pref = (k, d) => { try { return localStorage.getItem("nn:viz:" + k) || d; } catch (e) { return d; } };
  const setPref = (k, v) => { try { localStorage.setItem("nn:viz:" + k, v); } catch (e) { /* fine */ } };
  let style = pref("style", "ribbons");
  let palette = pref("palette", "neon");

  let spectrum = null, specFile = null, decodeToken = 0;
  const cache = new Map();              // file -> spectrum

  /* ---- the analysis --------------------------------------------------- */
  const HANN = new Float32Array(N);
  for (let i = 0; i < N; i++) HANN[i] = 0.5 - 0.5 * Math.cos((2 * Math.PI * i) / (N - 1));
  function fft(re, im) {                 // in place, radix 2
    for (let i = 1, j = 0; i < N; i++) {
      let bit = N >> 1;
      for (; j & bit; bit >>= 1) j ^= bit;
      j ^= bit;
      if (i < j) { [re[i], re[j]] = [re[j], re[i]]; [im[i], im[j]] = [im[j], im[i]]; }
    }
    for (let len = 2; len <= N; len <<= 1) {
      const ang = (-2 * Math.PI) / len, wr = Math.cos(ang), wi = Math.sin(ang);
      for (let i = 0; i < N; i += len) {
        let cr = 1, ci = 0;
        for (let k = 0; k < len / 2; k++) {
          const a = i + k, b = a + len / 2;
          const tr = re[b] * cr - im[b] * ci, ti = re[b] * ci + im[b] * cr;
          re[b] = re[a] - tr; im[b] = im[a] - ti; re[a] += tr; im[a] += ti;
          const ncr = cr * wr - ci * wi; ci = cr * wi + ci * wr; cr = ncr;
        }
      }
    }
  }
  /** pcm (mono) -> {fps, bands, data}: one character per level ("0" + 0..63). */
  async function spectrumOf(pcm, rate) {
    const hop = Math.max(1, Math.round(rate / FPS));
    const frames = Math.max(1, Math.floor((pcm.length - N) / hop));
    const edges = [];                   // 32 log-spaced bands, 40 Hz .. 16 kHz
    for (let b = 0; b <= NB; b++) edges.push(Math.min(N / 2 - 1, Math.max(1, Math.round((40 * Math.pow(16000 / 40, b / NB)) * N / rate))));
    const raw = new Float32Array(frames * NB);
    const re = new Float32Array(N), im = new Float32Array(N);
    for (let f = 0; f < frames; f++) {
      const off = f * hop;
      for (let i = 0; i < N; i++) { re[i] = (pcm[off + i] || 0) * HANN[i]; im[i] = 0; }
      fft(re, im);
      for (let b = 0; b < NB; b++) {
        const lo = edges[b], hi = Math.max(lo + 1, edges[b + 1]);
        let sum = 0;
        for (let k = lo; k < hi; k++) sum += Math.hypot(re[k], im[k]);
        raw[f * NB + b] = Math.log1p(sum / (hi - lo));
      }
      if (f % 400 === 399) await new Promise((r) => setTimeout(r, 0));   // never stall the page
    }
    // each band against its own loud end, so the treble moves as well as the bass
    const top = new Float32Array(NB);
    for (let b = 0; b < NB; b++) {
      const col = [];
      for (let f = 0; f < frames; f += 3) col.push(raw[f * NB + b]);
      col.sort((x, y) => x - y);
      top[b] = col[Math.floor(col.length * 0.96)] || 1;
    }
    /* ...but never against less than a quarter of the song's loudest band: a
       band with next to nothing in it would otherwise be blown up to full
       height by its own faint noise (a pure high note lit the bass). */
    const loudest = Math.max(...top);
    for (let b = 0; b < NB; b++) top[b] = Math.max(top[b], loudest * 0.25, 1e-6);
    let out = "";
    const prev = new Float32Array(NB);
    for (let f = 0; f < frames; f++) {
      let row = "";
      for (let b = 0; b < NB; b++) {
        let v = Math.min(1, Math.max(0, raw[f * NB + b] / top[b]));
        v = v * v;                                  // quiet stays quiet, peaks stand out
        v = Math.max(v, prev[b] * 0.82);            // falls back smoothly
        prev[b] = v;
        row += String.fromCharCode(48 + Math.round(v * 63));
      }
      out += row;
    }
    return {fps: FPS, bands: NB, frames, data: out};
  }
  /** A throwaway, NEVER-CONNECTED AudioContext, only to decode. */
  async function analyse(url) {
    let ac;
    try {
      const AC = window.AudioContext || window.webkitAudioContext;
      if (!AC) return null;
      const resp = await fetch(url);
      if (!resp.ok) return null;
      const bytes = await resp.arrayBuffer();
      ac = new AC();
      const buf = await ac.decodeAudioData(bytes);
      const a = buf.getChannelData(0), b = buf.numberOfChannels > 1 ? buf.getChannelData(1) : null;
      const mono = b ? a.map((v, i) => (v + b[i]) / 2) : a;
      return await spectrumOf(mono, buf.sampleRate);
    } catch (e) {
      return null;          // the visual falls back to its quiet motion; playback is untouched
    } finally {
      if (ac) { try { await ac.close(); } catch (e) { /* closed */ } }
    }
  }

  async function loadForCurrentTrack() {
    const t = CH.Player.current;
    if (!t) { spectrum = null; specFile = null; return; }
    if (specFile === t.file) return;
    if (cache.has(t.file)) { spectrum = cache.get(t.file); specFile = t.file; return; }
    spectrum = null;
    specFile = t.file;
    const mine = ++decodeToken;
    let url = t.url;
    if (!url && CH.Store.isDesktop() && window.pywebview?.api?.chords_audio_url) {
      try { const r = await window.pywebview.api.chords_audio_url(t.file); if (r && r.url) url = r.url; }
      catch (e) { /* stays empty */ }
    }
    if (!url) return;
    const spec = await analyse(url);
    if (mine !== decodeToken) return;   // a newer track started meanwhile
    if (spec) {
      cache.set(t.file, spec);
      if (cache.size > CACHE_CAP) cache.delete(cache.keys().next().value);
      spectrum = spec;
    }
  }

  function themeColors() {
    /* READ FROM THE CANVAS, NOT FROM :root.

       Cam: "change the visualizer so it matches each theme, for example
       the blue visualizer does not fit the theme in the image provided."

       --chord-btn and friends are declared on #ch-shell, and the theme
       bridge re-points them there too (--chord-btn: var(--accent), at the
       end of chords.css). :root has never had them. So asking
       document.documentElement returned an empty string every time, the
       || fallbacks fired every time, and the visualizer drew in a
       hardcoded #63B8F5 whatever theme the app was in.

       Measured, with the app in Hearth: ":root --chord-btn" empty,
       "#ch-shell --chord-btn" #C7392C, "canvas --chord-btn" #C7392C. The
       right colour was already there, an inheritance away, and nobody
       was asking the element that had it.

       The canvas rather than the shell by name: the canvas is inside the
       shell and inherits the same values, and it keeps working if the
       visualizer is ever drawn somewhere else.

       The fallbacks are the HOST's own accent family, off :root, which
       every theme defines -- so even if the music tokens disappeared the
       visualizer would still be in the theme's colours rather than in
       one fixed blue. A literal colour here is exactly what made this
       bug invisible.

       Both halves of this are load-bearing, and measurably so. I broke
       each on its own to find out:

         * reverted to reading :root with the old hardcoded fallbacks --
           all nine themes drew #63B8F5. Cam's screenshot, reproduced.
         * kept the :root read but added the --accent fallback -- the
           BARS came back to the theme, but gold fell through to --good
           and drew GREEN tips in every theme, because --gold is bridged
           from --star on #ch-shell and :root has never had it.

       So the --accent family rescues the bars and the canvas read
       rescues the gold. Neither alone is the fix.

       No document.documentElement in a variable here, deliberately, and
       test_one_app.py caught me putting one there. A tool taking hold of
       the page element is the exact shape Cranium's old zoom bug took --
       it kept it in `root` and then set .style.fontSize on it, scaling
       the whole app from inside one section. A read is harmless; the
       HABIT is not, because the next person to edit this has the page
       element already in a variable, one keystroke from writing to it.
       The page's own values are read through the one literal form the
       rule allows, below. */
    const el = canvas || document.getElementById("ch-shell");
    const own = el ? getComputedStyle(el) : null;
    const root = getComputedStyle(document.documentElement);
    const pick = (name, fallback) =>
      (own ? own.getPropertyValue(name).trim() : "")
      || root.getPropertyValue(fallback).trim()
      || root.getPropertyValue("--accent").trim()
      || "#C7392C";
    return {
      barColor: pick("--chord-btn", "--accent"),
      barColorDeep: pick("--chord-btn-deep", "--accent-deep"),
      gold: pick("--gold", "--good"),
    };
  }

  /* Colours: a picture palette (nnviz.js PALETTES), or "theme" -- the app's
     accent family, read at most once a second (the 2026-09-29 leak). */
  let colors = null, colorsAt = -Infinity;
  function paletteNow(tNow) {
    if (palette !== "theme") return NNViz.PALETTES[palette] || NNViz.PALETTES.neon;
    if (tNow - colorsAt > 1000) {
      const c = themeColors();
      if (!colors || c.barColor !== colors.barColor || c.gold !== colors.gold) {
        for (const k in vizCache) delete vizCache[k];
      }
      colors = c;
      colorsAt = tNow;
    }
    return {a: colors.barColorDeep, b: colors.barColor, c: colors.gold};
  }

  function resize() {
    if (!canvas) return;
    const rect = canvas.parentElement.getBoundingClientRect();
    const dpr = window.devicePixelRatio || 1;
    canvas.width = Math.max(1, Math.floor(rect.width * dpr));
    canvas.height = Math.max(1, Math.floor(rect.height * dpr));
    canvas.style.width = rect.width + "px";
    canvas.style.height = rect.height + "px";
    ctx2d = canvas.getContext("2d");
    if (ctx2d) ctx2d.scale(dpr, dpr);
    for (const k in vizCache) delete vizCache[k];   // sized for the old canvas
  }

  /** The bands to draw now: the song's spectrum at the playhead, or the quiet motion. */
  function bandsNow(tNow) {
    const cur = CH.Player.current;
    if (spectrum && cur && cur.file === specFile && CH.Player.playing) {
      const b = NNViz.bandsAt(spectrum, CH.Player.elapsed);
      if (b) return b;
    }
    return NNViz.idleBands(tNow / 1000, NB);
  }

  let lastDrawn = -Infinity, idleSince = 0;
  function paintFrame(tNow) {
    if (!ctx2d || !canvas) { rafId = null; return; }
    const w = canvas.clientWidth, h = canvas.clientHeight;
    if (!w || !h) {
      /* Music isn't on screen: no frames at all; look once a second. */
      rafId = null;
      asleep = setTimeout(() => {
        asleep = null;
        if (canvas && !rafId) rafId = requestAnimationFrame(paintFrame);
      }, 1000);
      return;
    }
    /* (the performance audit, 3 Nov 2026) silence: the quiet motion at 4 frames a second, and after a minute a still frame
       -- checked once a second, so music starting wakes it at once */
    if (CH.Player.playing) idleSince = 0; else if (!idleSince) idleSince = tNow;
    if (!CH.Player.playing && idleSince && tNow - idleSince > 60000 && lastDrawn > -Infinity) {
      rafId = null;
      asleep = setTimeout(() => { asleep = null; if (canvas && !rafId) rafId = requestAnimationFrame(paintFrame); }, 1000);
      return;
    }
    rafId = requestAnimationFrame(paintFrame);
    if (!CH.Player.playing && tNow - lastDrawn < 250) return;   // idle: 4 fps
    if (CH.Player.playing && window.NNLite && NNLite.on && tNow - lastDrawn < 66) return;   // Lite mode: 15 fps (lite.py)
    lastDrawn = tNow;
    ctx2d.clearRect(0, 0, w, h);
    NNViz.draw(ctx2d, style, bandsNow(tNow), tNow / 1000, w, h, paletteNow(tNow), vizCache);
  }

  const PALETTE_NAMES = [["neon", "Neon"], ["aurora", "Aurora"], ["sunset", "Sunset"], ["theme", "Theme"]];

  return {
    init() {},        // (it listened for the desktop Music widget, which went with the desktop widgets, 3 Nov 2026)
    STYLES: () => NNViz.STYLES.map((s) => s[0]),
    _test: {themeColors, spectrumOf, bandsNow, get style() { return style; }, get palette() { return palette; },
            get spectrum() { return spectrum; }},

    mount(mountEl) {
      el = mountEl;
      el.innerHTML = `
        <div class="viz-wrap">
          <div class="viz-modes" id="viz-modes">
            ${NNViz.STYLES.map(([k, n]) => `<button class="viz-mode-btn" data-mode="${k}">${n}</button>`).join("")}
          </div>
          <div class="viz-modes viz-pals" id="viz-pals">
            ${PALETTE_NAMES.map(([k, n]) => `<button class="viz-pal-btn" data-pal="${k}">${n}</button>`).join("")}
          </div>
          <canvas class="viz-canvas" id="viz-canvas"></canvas>
          <div class="viz-caption" id="viz-caption"></div>
        </div>`;
      canvas = el.querySelector("#viz-canvas");
      resize();
      resizeObserver = new ResizeObserver(() => resize());
      resizeObserver.observe(canvas.parentElement);

      const paintButtons = () => {
        el.querySelectorAll(".viz-mode-btn").forEach((b) => b.classList.toggle("on", b.dataset.mode === style));
        el.querySelectorAll(".viz-pal-btn").forEach((b) => b.classList.toggle("on", b.dataset.pal === palette));
      };
      paintButtons();
      el.querySelectorAll(".viz-mode-btn").forEach((b) => b.addEventListener("click", () => {
        style = b.dataset.mode; setPref("style", style); paintButtons();
      }));
      el.querySelectorAll(".viz-pal-btn").forEach((b) => b.addEventListener("click", () => {
        palette = b.dataset.pal; setPref("palette", palette);
        colorsAt = -Infinity; for (const k in vizCache) delete vizCache[k];
        paintButtons();
      }));

      const paintCaption = () => {
        const cap = el.querySelector("#viz-caption");
        if (!cap) return;
        const t = CH.Player.current;
        cap.textContent = t ? `${t.title}${t.artist ? " — " + t.artist : ""}` : "Nothing playing";
      };
      paintCaption();
      loadForCurrentTrack();
      playerUnsub = CH.Player.subscribe(() => { paintCaption(); loadForCurrentTrack(); });

      if (!rafId) rafId = requestAnimationFrame(paintFrame);
    },

    unmount() {
      if (rafId) { cancelAnimationFrame(rafId); rafId = null; }
      if (asleep) { clearTimeout(asleep); asleep = null; }
      if (resizeObserver) { resizeObserver.disconnect(); resizeObserver = null; }
      if (playerUnsub) { playerUnsub(); playerUnsub = null; }
      canvas = null;
      ctx2d = null;
      el = null;
    },
  };
})();

