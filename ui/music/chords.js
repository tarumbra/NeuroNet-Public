  async remote(cmd, arg) {
    const P = CH.Player;
    switch (cmd) {
      case "play": if (!P.playing) P.toggle(); break;
      case "pause": if (P.playing) P.toggle(); break;
      case "playpause": P.toggle(); break;
      case "stop": if (P.playing) P.toggle(); P.seek(0); break;
      case "next": P.next(); break;
      case "prev": P.prev(); break;
      case "seekTo": P.seek(Math.max(0, Number(arg) || 0)); break;
      case "volume": P.setVolume(arg); break;
      case "shuffle": P.setShuffle(!!arg); break;
      case "repeat": P.setRepeat(arg); break;
      /* The widget can ask the moment NeuroNet opens, before the library
         has loaded -- so wait for it. */
      case "open":
        if (!arg || !arg.id) return false;
        await startOnce();
        return this.play(arg.kind === "album" ? "album" : "playlist", arg.id);
      default: return false;
    }
    return true;
  },
