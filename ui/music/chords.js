/* The clock fits itself to the bar. It is the whole app's bar now, and with
   UI scale at 200% on an ordinary window the bar is too narrow for the
   player AND a full date and time: the ends of both spilled out of it. So
   each tick tries the full form first and steps down only if the bar
   actually overflows -- measured, not guessed from a width -- and it steps
   back up by itself when room returns (a wider window, a smaller scale).
   The player's controls never give way; the clock's detail does. */
const CLOCK_FORMS = [
  {weekday: "short", month: "short", day: "numeric",
   hour: "numeric", minute: "2-digit", second: "2-digit"},
  {month: "short", day: "numeric", hour: "numeric", minute: "2-digit"},
  {hour: "numeric", minute: "2-digit"},
];
/* Ticking without leaking (2026-09-29, the memory-leak fix -- see drawColors).
   Setting textContent every second threw away a text node a second, and
   the fit test forced a full layout every second, all day, NeuroNet hidden
   or not. Now the one text node is rewritten in place; the fit is measured
   again only when the text's length changes (the date rolls over, a form
   steps up or down) or once a minute to notice room coming back, and not
   at all while the bar isn't drawn. */
/* (the performance audit, 3 Nov 2026) the formatters made once: toLocaleString with options builds a new one every call,
   and in QtWebEngine each left about 47 KB behind -- once a second, all day, hidden or not: 160 MB an hour, 1.8 GB in a
   working day. Measured in the sample NeuroNet: made once, it doesn't grow at all. */
const CLOCK_FMT = CLOCK_FORMS.map((o) => new Intl.DateTimeFormat(undefined, o));
/* ...and the second hand only while NeuroNet is the window in front: hidden, or behind another, it shows the minutes and
   is painted once a minute (each repaint left a little behind too -- 1 MB a minute -- so a NeuroNet tucked away all day
   now does a sixtieth of the work) */
const CLOCK_MIN = CLOCK_FORMS.map((o) => { const c = Object.assign({}, o); delete c.second; return new Intl.DateTimeFormat(undefined, c); });
let clockFocused = true, clockMinute = -1;
let clockForm = 0;
let clockLen = -1;
let clockMeasured = 0;
function paintClock() {
  const el = document.getElementById("ch-top-bar-clock");
  if (!el) return;
  const bar = document.getElementById("ch-top-bar");
  const now = new Date();
  const write = (s) => {
    if (el.firstChild && el.firstChild.nodeType === 3 && !el.firstChild.nextSibling) {
      if (el.firstChild.nodeValue !== s) el.firstChild.nodeValue = s;
    } else {
      el.textContent = s;
    }
  };
  const FM = clockFocused ? CLOCK_FMT : CLOCK_MIN;
  let text = FM[clockForm].format(now);
  const shown = !!bar && bar.getClientRects().length > 0;
  if (shown && (text.length !== clockLen || now - clockMeasured > 60000)) {
    clockMeasured = now;
    for (let i = 0; i < CLOCK_FORMS.length; i++) {
      text = FM[i].format(now);
      write(text);
      clockForm = i;
      if (bar.scrollWidth <= bar.clientWidth + 1) break;
    }
    clockLen = text.length;
    return;
  }
  write(text);
}

