/* ======================================================================
   NeuroNet on the Linux media bus.
   ======================================================================
   Cam: "a top bar music player for NeuroNet? That uses the music library
   file from neuronet?" The bar widget, Omarchy's audio panel and the media
   keys all find NeuroNet over MPRIS (mpris.py). That side holds no player
   of its own: it is told what CH.Player is doing (report) and hands every
   button press back to CH.Player (SS.Music.remote, below).

   Reports go on every change the player makes, gathered for a moment so a
   track change -- which repaints several times -- is one message. Nothing
   is sent per tick: the bus works the position out itself between reports,
   and a seek is reported the moment it happens. */
const Mpris = (() => {
  let timer = null, last = "", seeked = false;
  function state() {
    const P = CH.Player, t = P.current;
    return {
      status: !t ? "Stopped" : (P.playing ? "Playing" : "Paused"),
      file: t ? t.file : "", title: t ? (t.title || t.file) : "",
      artist: t ? (t.artist || "") : "", album: t ? (t.album || "") : "",
      art: t ? (t.art || "") : "", length: P.duration || (t && t.duration) || 0,
      position: P.elapsed, volume: P.volume, shuffle: P.shuffle, repeat: P.repeat,
      favourite: !!(t && CH.tools.chords && CH.tools.chords.isFavourite && CH.tools.chords.isFavourite(t.file)),
    };
  }
  function send() {
    timer = null;
    const api = window.pywebview && window.pywebview.api;
    if (!api || typeof api.music_mpris_update !== "function") return;
    const s = state();
    /* Same as last time, apart from the clock? Nothing to say. */
    const sig = JSON.stringify({...s, position: 0});
    if (sig === last && !seeked) return;
    last = sig;
    s.seeked = seeked; seeked = false;
    Promise.resolve(api.music_mpris_update(s)).catch(() => {});
  }
  function schedule(kind) {
    if (kind === "seeked") seeked = true;
    if (!timer) timer = setTimeout(send, 120);
  }
  CH.Player._onState = schedule;
  /* The first report is what tells the bus the page is ready for
     commands, so it goes out as soon as the bridge exists. */
  if (window.pywebview && window.pywebview.api) schedule();
  else window.addEventListener("pywebviewready", () => schedule(), {once: true});
  return {state, flush: send};
})();

