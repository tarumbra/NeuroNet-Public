/* ==========================================================================
   CH.RightPanel — the toggleable right-hand playlist panel.

   Cam: "the right side bar will have a drop down menu where i can
   select a playlist and a icon when clicked allows me to create a
   playlist (Think playlist management)... The ability to drag and
   drop a song into the right panel and add it to the playlist."

   This is a second UI surface over the EXACT SAME playlist data
   chords.js's own Playlists section already owns — chords.js stays
   the single source of truth (getPlaylists/createPlaylist/
   addFilesToPlaylist/removeFromPlaylist, all exposed on CH.tools.chords),
   this file just renders a compact view of it and reacts to
   subscribeToData() so creating a playlist from either surface keeps
   both in sync.

   Mounted ONCE at boot (chords_shell.js) and left in the DOM — the
   panel's own selected-playlist state needs to survive being closed
   (width:0) and reopened, and #cc-sidebar-right lives outside #app
   for exactly that reason (see index.html).
   ========================================================================== */
CH.RightPanel = (() => {
  const esc = (s) => String(s ?? "").replace(/&/g, "&amp;")
    .replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const escA = (s) => esc(s).replace(/"/g, "&quot;");

  let el = null, dataSub = null;            // (dataSub: the one data subscription, 3 Nov)
  let selectedId = null;
  const chords = () => CH.tools.chords;

  function currentPlaylist() {
    const list = chords().getPlaylists();
    if (selectedId && list.find((p) => p.id === selectedId)) {
      return list.find((p) => p.id === selectedId);
    }
    return list[0] || null;
  }

  function render() {
    if (!el) return;
    const playlists = chords().getPlaylists();
    const p = currentPlaylist();
    if (p) selectedId = p.id;
    const tracks = p ? (p.files || []).map((f) => chords()._test.trackOf(f)) : [];

    el.innerHTML = `
      <div class="rp-wrap">
        <div class="rp-head">
          <select class="input rp-select" id="rp-pl-select" ${
            playlists.length ? "" : "disabled"}>
            ${playlists.length ? playlists.map((x) => `
              <option value="${escA(x.id)}" ${x.id === selectedId ? "selected" : ""}>${esc(x.name)}</option>`).join("")
              : `<option>No playlists yet</option>`}
          </select>
          <button class="chord-btn sm" id="rp-new" type="button"
                  title="Create a playlist" aria-label="Create a playlist">+</button>
        </div>
        <div class="rp-drop" id="rp-drop">
          ${p ? `
            <div class="rp-pl-title">${esc(p.name)}</div>
            <div class="rp-tracks">${tracks.map((t, i) => `
              <div class="rp-track">
                <div class="rp-track-main">
                  <div class="rp-track-t">${esc(t.title)}</div>
                  <div class="rp-track-a">${esc(t.artist || "")}</div>
                </div>
                <button data-rm="${i}" title="Remove from playlist">&#10005;</button>
              </div>`).join("") ||
              `<div class="rp-empty">Drag songs from your Library here.</div>`}
            </div>
            <button class="btn btn-save rp-play-btn" id="rp-play">Play this playlist</button>
          ` : `<div class="rp-empty">Create a playlist to get started.</div>`}
        </div>
      </div>`;

    const sel = el.querySelector("#rp-pl-select");
    if (sel) sel.onchange = () => { selectedId = sel.value; render(); };
    el.querySelector("#rp-new").onclick = () => openNewPlaylistDialog();
    const playBtn = el.querySelector("#rp-play");
    if (playBtn) playBtn.onclick = () => {
      if (!tracks.length) { CH.toast("That playlist is empty.", "error"); return; }
      CH.Player.playQueue(tracks, 0);
      CH.toast(`Playing "${p.name}".`);
    };
    el.querySelectorAll("[data-rm]").forEach((b) =>
      b.onclick = () => {
        chords().removeFromPlaylist(p.id, Number(b.dataset.rm));
        render();
      });

    wireDropZone();
  }

  /** A real, themed dialog — not window.prompt(), which isn't reliable
      inside pywebview's own WebKitGTK webview (the same real reason
      Cortex's own "New deck" dialog was fixed the same way). Uses the
      same shared #modal-veil every other dialog in the app already
      does, so it looks and behaves like the rest of Chords rather
      than a native browser prompt. */
  function openNewPlaylistDialog() {
    const veil = document.getElementById("ch-modal-veil");
    veil.innerHTML = `
      <div class="modal" role="dialog" aria-modal="true">
        <h3>New playlist</h3>
        <label class="dlg-label">Name</label>
        <input class="input" id="rp-pl-name" style="width:100%"
               placeholder="e.g. Deep Work">
        <div class="row">
          <button class="btn btn-quiet" data-act="cancel">Cancel</button>
          <button class="btn btn-save" data-act="create">Create</button>
        </div>
      </div>`;
    const close = () => { veil.classList.remove("open"); veil.innerHTML = ""; };
    veil.onclick = (e) => { if (e.target === veil) close(); };
    veil.querySelector("[data-act=cancel]").onclick = close;
    const input = veil.querySelector("#rp-pl-name");
    const create = () => {
      const name = input.value.trim();
      if (!name) { input.focus(); return; }
      const created = chords().createPlaylist(name);
      selectedId = created.id;
      close();
      render();
    };
    veil.querySelector("[data-act=create]").onclick = create;
    input.addEventListener("keydown", (e) => { if (e.key === "Enter") create(); });
    veil.classList.add("open");
    setTimeout(() => input.focus(), 30);
  }

  function wireDropZone() {
    const zone = el.querySelector("#rp-drop");
    if (!zone) return;
    zone.addEventListener("dragover", (e) => {
      /* Only ever treat this as a valid drop target when there's a
         real, selected playlist to add to, and the drag itself is
         genuinely carrying one of Chords' own track files — a plain
         file-manager drag or anything else stays a normal, refused
         drop rather than silently accepted and lost. */
      if (!currentPlaylist()) return;
      if (!e.dataTransfer.types.includes("application/x-chords-file")) return;
      e.preventDefault();
      e.dataTransfer.dropEffect = "copy";
      zone.classList.add("rp-drop-over");
    });
    zone.addEventListener("dragleave", () => zone.classList.remove("rp-drop-over"));
    zone.addEventListener("drop", (e) => {
      zone.classList.remove("rp-drop-over");
      const p = currentPlaylist();
      const file = e.dataTransfer.getData("application/x-chords-file");
      if (!p || !file) return;
      e.preventDefault();
      chords().addFilesToPlaylist(p.id, [file]);
      CH.toast(`Added to "${p.name}".`);
      render();
    });
  }

  return {
    mount(mountEl) {
      el = mountEl;
      /* once, not on every mount (the performance audit, 3 Nov): each visit added another subscriber, so one change to the
         data re-drew the panel once for every visit since NeuroNet opened */
      if (!dataSub) dataSub = chords().subscribeToData(() => { if (el && el.isConnected) render(); });
      render();
    },
  };
})();

